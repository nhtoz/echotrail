"""Tamper-evident trace store.

Each session is an append-only JSONL file. Every event embeds the SHA-256
hash of the previous event line, forming a hash chain. Any edit, deletion,
or reordering of past events breaks verification from that point forward.

Appends are serialised per session (a thread lock plus an OS file lock), so
concurrent writers (parallel tool calls, the MCP proxy's two relay threads,
several processes sharing one trace directory) can never fork the chain.

What the chain alone cannot prove: that nothing was cut off the end, or that
the whole file was not regenerated by whoever holds it. A session that ends
without `session_end` is reported as unsealed; external anchoring (anchor.py)
covers wholesale rewrites.
"""

from __future__ import annotations

import hashlib
import json
import os
import threading
import time
import uuid
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterator

try:  # POSIX advisory file locks for multi-process writers
    import fcntl
except ImportError:  # pragma: no cover - Windows: thread lock only
    fcntl = None  # type: ignore[assignment]

GENESIS = "0" * 64
SEAL_TYPES = {"session_end"}

_locks: dict[str, threading.Lock] = {}
_locks_guard = threading.Lock()


def _canonical(obj: dict[str, Any]) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def _thread_lock(path: Path) -> threading.Lock:
    key = str(path.resolve())
    with _locks_guard:
        lock = _locks.get(key)
        if lock is None:
            lock = _locks[key] = threading.Lock()
        return lock


@contextmanager
def _locked(path: Path, mode: str) -> Iterator[Any]:
    with _thread_lock(path):
        with open(path, mode, encoding="utf-8") as f:
            if fcntl is not None:
                fcntl.flock(f.fileno(), fcntl.LOCK_EX)
            try:
                yield f
            finally:
                if fcntl is not None:
                    fcntl.flock(f.fileno(), fcntl.LOCK_UN)


def _last_line(f: Any) -> str | None:
    """Return the last non-empty line of an open text file (reads from the end)."""
    f.seek(0, os.SEEK_END)
    end = f.tell()
    if end == 0:
        return None
    buf, pos, chunk = b"", end, 4096
    raw = f.buffer
    while pos > 0:
        step = min(chunk, pos)
        pos -= step
        raw.seek(pos)
        buf = raw.read(step) + buf
        lines = [ln for ln in buf.split(b"\n") if ln.strip()]
        if len(lines) >= 2 or (pos == 0 and lines):
            return lines[-1].decode("utf-8")
    return None


@dataclass
class VerificationResult:
    ok: bool
    events: int
    first_bad_seq: int | None = None
    reason: str | None = None
    sealed: bool | None = None  # True if the chain ends with session_end


class TraceStore:
    """Append-only, hash-chained session store on the local filesystem."""

    def __init__(self, root: str | Path = "./traces"):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)

    # -- writing ---------------------------------------------------------

    def create_session(self, name: str, metadata: dict[str, Any] | None = None) -> str:
        session_id = time.strftime("%Y%m%d-%H%M%S") + "-" + uuid.uuid4().hex[:8]
        header = {
            "seq": 0,
            "type": "session_start",
            "ts": time.time(),
            "session_id": session_id,
            "name": name,
            "metadata": metadata or {},
            "prev_hash": GENESIS,
        }
        header["hash"] = self._hash_event(header)
        with open(self._path(session_id), "x", encoding="utf-8") as f:  # never overwrite
            f.write(json.dumps(header, ensure_ascii=False) + "\n")
        return session_id

    def append(self, session_id: str, event_type: str, payload: dict[str, Any]) -> dict[str, Any]:
        path = self._path(session_id)
        with _locked(path, "a+") as f:
            line = _last_line(f)
            if line is None:
                raise ValueError(f"empty session file: {path}")
            last = json.loads(line)
            event = {
                "seq": last["seq"] + 1,
                "type": event_type,
                "ts": time.time(),
                "session_id": session_id,
                "payload": payload,
                "prev_hash": last["hash"],
            }
            event["hash"] = self._hash_event(event)
            f.seek(0, os.SEEK_END)
            f.write(json.dumps(event, ensure_ascii=False) + "\n")
            f.flush()
            os.fsync(f.fileno())
        return event

    # -- reading ---------------------------------------------------------

    def sessions(self) -> list[dict[str, Any]]:
        out = []
        for p in sorted(self.root.glob("*.jsonl"), reverse=True):
            events, malformed = self._read_tolerant(p.stem)
            if not events and not malformed:
                continue
            head = events[0] if events else {}
            v = self.verify(p.stem)
            out.append(
                {
                    "session_id": head.get("session_id", p.stem),
                    "name": head.get("name", "(unreadable)"),
                    "started": head.get("ts", p.stat().st_mtime),
                    "events": len(events) + malformed,
                    "verified": v.ok,
                    "sealed": v.sealed,
                    "risk": sum(
                        e.get("payload", {}).get("_risk", 0) for e in events[1:]
                        if isinstance(e.get("payload"), dict)
                    ),
                }
            )
        return out

    def read(self, session_id: str) -> Iterator[dict[str, Any]]:
        with open(self._path(session_id), encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    yield json.loads(line)

    def verify(self, session_id: str) -> VerificationResult:
        prev_hash = GENESIS
        count = 0
        last_type = None
        try:
            f = open(self._path(session_id), encoding="utf-8")
        except FileNotFoundError:
            return VerificationResult(False, 0, None, "session not found")
        with f:
            for line in f:
                if not line.strip():
                    continue
                try:
                    event = json.loads(line)
                    if not isinstance(event, dict):
                        raise ValueError("not an object")
                except ValueError:
                    return VerificationResult(False, count, count, "malformed line (not valid JSON event)")
                claimed = event.get("hash")
                body = {k: v for k, v in event.items() if k != "hash"}
                if event.get("prev_hash") != prev_hash:
                    return VerificationResult(False, count, event.get("seq"), "chain broken (prev_hash mismatch)")
                if self._hash_event(body) != claimed:
                    return VerificationResult(False, count, event.get("seq"), "event content altered (hash mismatch)")
                prev_hash = claimed
                count += 1
                last_type = event.get("type")
        if count == 0:
            return VerificationResult(False, 0, None, "empty session")
        return VerificationResult(True, count, sealed=last_type in SEAL_TYPES)

    # -- internals -------------------------------------------------------

    def _read_tolerant(self, session_id: str) -> tuple[list[dict[str, Any]], int]:
        events, bad = [], 0
        try:
            with open(self._path(session_id), encoding="utf-8") as f:
                for line in f:
                    if not line.strip():
                        continue
                    try:
                        events.append(json.loads(line))
                    except ValueError:
                        bad += 1
        except OSError:
            pass
        return events, bad

    def _path(self, session_id: str) -> Path:
        return self.root / f"{session_id}.jsonl"

    @staticmethod
    def _hash_event(body: dict[str, Any]) -> str:
        return hashlib.sha256(_canonical(body)).hexdigest()
